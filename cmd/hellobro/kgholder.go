package main

// kitty's Unicode placeholders: a program puts an image somewhere without
// a cursor, as text. It places it virtually (U=1), then writes cells of
// U+10EEEE where it shows: the foreground color is the image's id, the
// underline color the placement's, and diacritics after it say the
// cell's row and column in the image (and the id's top byte). A cell
// without them takes its row from the one on its left, and the next
// column. Being text, it scrolls, moves with tmux's panes and goes with
// a clear like any.

import (
	"image/color"
	"unicode/utf8"

	uv "github.com/charmbracelet/ultraviolet"
	"github.com/charmbracelet/x/ansi"
)

const kgHolderRune = 0x10EEEE

// kgHolder is a placeholder cell: which image, which placement (or 0),
// and where in it.
type kgHolder struct {
	id, pid  uint32
	row, col int
}

// isKgHolder says whether a cell is a placeholder: U+10EEEE, 4 bytes.
func isKgHolder(c *uv.Cell) bool {
	return c != nil && len(c.Content) >= 4 && c.Content[0] == 0xf4 && c.Content[1] == 0x8e && c.Content[2] == 0xbb && c.Content[3] == 0xae
}

// kgHolderOf reads placeholder cell c, the one on its left being left
// (if it was one).
func kgHolderOf(c *uv.Cell, left *kgHolder) (kgHolder, bool) {
	if !isKgHolder(c) || c.Style.Fg == nil {
		return kgHolder{}, false
	}
	h := kgHolder{id: kgColorID(c.Style.Fg)}
	if c.Style.UnderlineColor != nil {
		h.pid = kgColorID(c.Style.UnderlineColor)
	}
	var ds []int
	for s := c.Content[4:]; s != "" && len(ds) < 3; {
		r, n := utf8.DecodeRuneInString(s)
		s = s[n:]
		d, ok := kgDiacritic[r]
		if !ok {
			break
		}
		ds = append(ds, d)
	}
	same := left != nil && left.pid == h.pid && left.id&0xffffff == h.id
	switch len(ds) {
	case 0:
		if same {
			h.id, h.row, h.col = left.id, left.row, left.col+1
		}
	case 1:
		h.row = ds[0]
		if same && left.row == h.row {
			h.id, h.col = left.id, left.col+1
		}
	default:
		h.row, h.col = ds[0], ds[1]
		if len(ds) == 3 {
			h.id |= uint32(ds[2]) << 24
		} else if same && left.row == h.row && left.col+1 == h.col {
			h.id = left.id
		}
	}
	return h, true
}

// kgColorID is the number a color says: 24 bits, or 8 as one of the 256.
func kgColorID(c color.Color) uint32 {
	switch c := c.(type) {
	case ansi.IndexedColor:
		return uint32(c)
	case ansi.BasicColor:
		return uint32(c)
	}
	r, g, b, _ := c.RGBA()
	return r>>8<<16 | g>>8<<8 | b>>8
}

// virtualFor is the virtual placement the placeholders of image id (and
// placement pid, if not 0) show: the latest.
func (g *kittyGfx) virtualFor(id, pid uint32) *kgPlace {
	var found *kgPlace
	for _, pl := range g.places {
		if pl.virtual && pl.img.id == id && (pid == 0 || pl.pid == pid) && (found == nil || pl.seq > found.seq) {
			found = pl
		}
	}
	return found
}

// kgDiacritic is each diacritic's number: kitty's rowcolumn-diacritics.txt.
